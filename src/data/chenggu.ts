const DIGITS = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
/** 43 钱 → “四两三钱” */
export function formatWeight(qian: number): string {
  const liang = Math.floor(qian / 10);
  const q = qian % 10;
  return `${liang ? DIGITS[liang] + '两' : ''}${q ? DIGITS[q] + '钱' : ''}` || '零';
}

export function boneTone(qian: number): { tone: Tone; level: string } {
  if (qian < 30) return { tone: 'xiong', level: '清苦' };
  if (qian < 40) return { tone: 'ping', level: '平顺' };
  if (qian < 50) return { tone: 'ji', level: '小康' };
  if (qian < 60) return { tone: 'ji', level: '富足' };
  return { tone: 'ji', level: '大贵' };
}

